#!/usr/bin/env node
// Writes web/src/lib/api/shared/emoji-data.ts from emoji-datasource's emoji.json (iamcal, MIT), the data behind Slack's emoji names.
// Usage: npm pack emoji-datasource && tar xzf emoji-datasource-*.tgz && node scripts/emoji-data.mjs package/emoji.json
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const source = process.argv[2];
if (!source) throw new Error("Usage: node scripts/emoji-data.mjs <emoji-datasource emoji.json>");
const version = JSON.parse(readFileSync(new URL("package.json", new URL(".", `file://${source}`)), "utf8")).version;
const rows = JSON.parse(readFileSync(source, "utf8"))
  .filter(e => e.category !== "Component" && e.has_img_apple)
  .sort((a, b) => a.sort_order - b.sort_order);
const order = ["Smileys & Emotion", "People & Body", "Animals & Nature", "Food & Drink", "Travel & Places", "Activities", "Objects", "Symbols", "Flags"];
const char = e => String.fromCodePoint(...e.unified.split("-").map(h => parseInt(h, 16)));
const body = order.map(category => {
  const words = e => [...new Set((e.name ?? "").toLowerCase().split(/[^a-z0-9]+/).filter(w => w && !e.short_names.some(n => n.split(/[_-]/).includes(w))))];
  const list = rows.filter(e => e.category === category).map(e => [char(e), e.short_names.join(","), ...words(e)].join(" "));
  return `  [${JSON.stringify(category)}, ${JSON.stringify(list.join("\n"))}],`;
});
const out = [
  `// Generated by apps/chat/scripts/emoji-data.mjs from emoji-datasource ${version} (Cal Henderson, MIT), the names Slack uses. Do not edit.`,
  "/** Each category, in Slack's order, with one line per emoji: the emoji, its names comma separated, and the words of its Unicode name that the names lack, space separated. */",
  "export const EMOJI_DATA: readonly (readonly [string, string])[] = [",
  ...body,
  "];",
  "",
].join("\n");
const target = fileURLToPath(new URL("../web/src/lib/api/shared/emoji-data.ts", import.meta.url));
writeFileSync(target, out);
console.log(`wrote ${rows.length} emoji to ${target}`);
